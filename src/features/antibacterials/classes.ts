export interface Fact {
  topic: Topic
  text: string
  /** Matters for a haematology patient: marrow, kidney, interaction with immunosuppressants. */
  heme?: boolean
}

export interface AbxDrug {
  name: string
  /** Id of the drug card in `data/drugs`, when there is one. */
  drugId?: string
  facts: Fact[]
}

export interface AbxClass {
  id: string
  title: string
  /** Page slugs under MSD_BASE the facts of this class come from. */
  pages: string[]
  facts: Fact[]
  drugs: AbxDrug[]
}

const f = (topic: Topic, text: string, heme = false): Fact =>
  heme ? { topic, text, heme } : { topic, text }

