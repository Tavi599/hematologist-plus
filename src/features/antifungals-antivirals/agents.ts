export type SourceId = keyof typeof SOURCES

export interface Fact {
  topic: Topic
  text: string
  /** Matters for a haematology patient: marrow, kidney, interaction with chemo or immunosuppressants. */
  heme?: boolean
  /** Where the fact comes from, when not from the first source of its class. */
  src?: SourceId
}

/** What the State Register holds for a drug the catalog has no card for. */
export interface RegisterEntry {
  /** `current`: a current registration exists; `none`: no current registration found. */
  status: 'current' | 'none'
  note: string
}

export interface AfavDrug {
  name: string
  /** Id of the drug card in `data/drugs`, when there is one. */
  drugId?: string
  /** Only for a drug without a card: what the State Register holds. */
  register?: RegisterEntry
  facts: Fact[]
}

export type Group = 'antifungal' | 'antiviral'

export interface AfavClass {
  id: string
  group: Group
  title: string
  sources: SourceId[]
  facts: Fact[]
  drugs: AfavDrug[]
}

