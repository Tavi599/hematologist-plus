/**
 * Antifungal and antiviral drugs as a reference of short, checkable facts: class → drug → fact,
 * built the same way as the antibacterial reference. The facts are cut out of the MSD Manual
 * Professional (Ukrainian edition) pages named in each class and of the supportive-care pages of
 * NCCN guidelines, written as our own terse points; nothing is a retelling and nothing is added
 * from outside them. MSD gives almost no doses for these drugs: a dose appears only where a source
 * itself gives a number, otherwise the card says «без розрахунку».
 *
 * A drug that has a card in `data/drugs` carries its `drugId` and shows its availability from
 * the catalog. A drug without a card says what the State Register holds for it (`register`).
 * Where a value differs from what the catalog already holds, the difference is listed in
 * `DISCREPANCIES`; neither side is rewritten.
 */

